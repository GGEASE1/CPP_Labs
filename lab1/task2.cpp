#include <iostream>
using namespace std;

int main()
{
    // Объявляем массив
    int arr[] = {100, 200, 300};

    // Указатель на первый элемент массива
    int *p1 = arr;

    // Указатель на третий элемент массива
    int *p2 = &arr[2];

    // Вывод адреса и значения первого элемента
    cout << "p1 address: " << p1 << ", value: " << *p1 << endl;

    // Переход к следующему элементу массива
    p1++;

    // Теперь p1 указывает на второй элемент
    cout << "After p1++ -> value: " << *p1 << endl;

    // Вывод значения третьего элемента
    cout << "p2 value: " << *p2 << endl;

    // Разность указателей (расстояние между элементами)
    cout << "Distance (p2 - p1): " << p2 - p1 << endl;

    return 0;
}